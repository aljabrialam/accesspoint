GAP = 0.3         # silence between consecutive spoken lines
AFTER_TAP = 0.4   # screen transition before the app speaks
MIC_OPEN = 0.6    # time between opening the mic and tapping a phrase


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, **kw)


def duration(path):
    return float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                                capture_output=True, text=True, check=True).stdout)


def app_clips():
    src = (MOBILE / "src/voice/clips.generated.ts").read_text()
    return {json.loads(f'"{t}"'): MOBILE / "assets/voice" / f for t, f in re.findall(r'^  "(.*)": require\(\'\.\./\.\./assets/voice/(\w+\.mp3)\'\)', src, re.M)}


def tts(text, voice):
    name, rate = voice
    out = HERE / "audio" / f"{hashlib.sha1(f'{name}|{rate}|{text}'.encode()).hexdigest()[:16]}.mp3"
    if not out.exists():
        out.parent.mkdir(exist_ok=True)
        raw = out.with_suffix(".raw.mp3")
        for attempt in range(3):
            try:
                run([sys.executable, "-m", "edge_tts", "--voice", name, f"--rate={rate}", "--text", text, "--write-media", str(raw)], capture_output=True)
                break
            except subprocess.CalledProcessError:
                if attempt == 2:
                    raise
        run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(raw), "-af", TIGHTEN, str(out)])
        raw.unlink()
    return out


def line_audio(beat, clips):
    kind = beat[0]
    if kind == "narr":
        return tts(beat[1], NARRATOR)
    if kind == "app":
        if beat[1] not in clips:
            sys.exit(f"No app clip for: {beat[1]!r}. Run `npm run voice:generate` in mobile/ after editing scenario speech.")
        return clips[beat[1]]
    if kind == "say":
        return tts(beat[3], PEOPLE[beat[2]])
    return None


# ---------------------------------------------------------------- flows
def pause(ms):
    return f'- extendedWaitUntil:\n    visible: "__pause__"\n    timeout: {int(ms)}\n    optional: true\n'


def cmd_flows():
    clips = app_clips()
    head = "appId: host.exp.Exponent\n---\n"
    for d in DEMOS:
        link, wait, pre_taps = d["prep"]
        prep = head + "- runFlow: ../../mobile/.maestro/subflows/close-open-guide.yaml\n"
        prep += f"- openLink: exp://127.0.0.1:8081/--/{link}\n- extendedWaitUntil:\n    visible: \"{wait}\"\n    timeout: 20000\n- waitForAnimationToEnd\n"
        for t in pre_taps:
            prep += f'- tapOn: {{ id: "{t}" }}\n- waitForAnimationToEnd\n'
        rec = head
        first_tap = True
        for b in d["beats"]:
            if b[0] in ("narr", "app"):
                rec += pause((duration(line_audio(b, clips)) + GAP + (0.6 if first_tap else 0.3)) * 1000)
            elif b[0] == "tap":
                rec += f'- tapOn: {{ id: "{b[1]}" }}\n' + pause(AFTER_TAP * 1000)
                first_tap = False
            elif b[0] == "say":
                rec += '- tapOn: { id: "voice-mic" }\n' + pause(MIC_OPEN * 1000)
                rec += pause((duration(line_audio(b, clips)) + 0.1) * 1000) + f'- tapOn: {{ id: "{b[1]}" }}\n' + pause(AFTER_TAP * 1000)
                first_tap = False
        rec += pause(1200)
        (DEMO / "flows" / f"prep-{d['id']}.yaml").write_text(prep)
        (DEMO / "flows" / f"rec-{d['id']}.yaml").write_text(rec)
    print(f"wrote flows for {', '.join(d['id'] for d in DEMOS)}")


# ---------------------------------------------------------------- timeline
def screen_changes(path):
    out = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-vf", "select='gt(scene,0.05)',showinfo", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    times, merged, prev = [float(t) for t in re.findall(r"pts_time:([0-9.]+)", out)], [], None
    for t in times:
        if prev is None or t - prev > 0.6:  # one transition registers as a run of changes; keep its first frame
            merged.append(t)
        prev = t
    return merged


def cmd_timeline():
    clips = app_clips()
    (DEMO / "clips/cfr").mkdir(parents=True, exist_ok=True)
    (HERE / "clips").mkdir(exist_ok=True)

    t = 0.0
    scenes, captions, audio, demos, clip_slots = {}, [], [], [], []

    def add_static(scene_list):
        nonlocal t
        for sid, section, badge, min_dur, lines in scene_list:
            cursor, marks = 0.3, []
            for kind, text in lines:
                a = tts(text, HERO_VOICE if kind == "hero" else NARRATOR)
                marks.append(round(cursor, 3))
                captions.append(dict(start=round(t + cursor, 3), end=round(t + cursor + duration(a) + 0.2, 3), kind="narr", text=text))
                audio.append((t + cursor, a, "voice"))
                cursor += duration(a) + LINE_GAP
            dur = max(min_dur, cursor - LINE_GAP + TAIL.get(sid, 0.5))
            scenes[sid] = dict(start=round(t, 3), end=round(t + dur, 3), section=section, badge=badge, marks=marks)
            t += dur

    add_static(INTRO)
    for d in DEMOS:
        raw, cfr = DEMO / "clips/raw" / f"{d['id']}.mp4", DEMO / "clips/cfr" / f"{d['id']}.mp4"
        run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(raw), "-vf", "fps=30", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-an", str(cfr)])
        changes = screen_changes(cfr)
        n_taps = sum(1 if b[0] == "tap" else 2 for b in d["beats"] if b[0] in ("tap", "say"))
        if len(changes) < n_taps:
            sys.exit(f"{d['id']}: expected {n_taps} screen changes, found {len(changes)} ({changes}). Re-record this clip.")
        changes = changes[:n_taps]

        # Lay out spoken lines: lines before the first tap play from the start; later lines follow their tap.
        pre = [b for b in d["beats"][: next(i for i, b in enumerate(d["beats"]) if b[0] in ("tap", "say"))]]
        pre_len = 0.4 + sum(duration(line_audio(b, clips)) + GAP for b in pre)
        clip_start = changes[0] - pre_len
        if clip_start < 0:
            sys.exit(f"{d['id']}: not enough footage before the first tap ({changes[0]:.1f}s, need {pre_len:.1f}s).")
        rel, ci, lines, beats_ui = 0.4, 0, [], [(0.0, *d["status"])]
        cursor = 0.4
        for b in d["beats"]:
            if b[0] == "tap":
                tap_rel = changes[ci] - clip_start
                ci += 1
                beats_ui.append((round(tap_rel, 3), *b[2]))
                cursor = max(cursor, tap_rel + AFTER_TAP)
            elif b[0] == "say":
                mic_rel, chip_rel = changes[ci] - clip_start, changes[ci + 1] - clip_start
                ci += 2
                a = line_audio(b, clips)
                lines.append((max(mic_rel + 0.25, chip_rel - duration(a) - 0.05), b, a))
                beats_ui.append((round(chip_rel, 3), *b[4]))
                cursor = max(cursor, chip_rel + AFTER_TAP)
            else:
                a = line_audio(b, clips)
                lines.append((cursor, b, a))
                cursor += duration(a) + GAP
        scene_len = max(cursor + 0.5, changes[-1] - clip_start + 1.5)
        if clip_start + scene_len > duration(cfr):
            sys.exit(f"{d['id']}: recording too short for the planned audio. Re-run `python3 build.py flows` and re-record.")

        run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(cfr), "-ss", f"{clip_start:.3f}", "-t", f"{scene_len:.3f}", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-an", str(HERE / "clips" / f"{d['id']}.mp4")])
        scenes[f"demo-{d['id']}"] = dict(start=round(t, 3), end=round(t + scene_len, 3), section=d["section"], badge="Scenario mode, demo kiosk we built")
        clip_slots.append(dict(name=d["id"], start=round(t, 3), end=round(t + scene_len, 3)))
        demos.append(dict(start=round(t, 3), end=round(t + scene_len, 3), count=d["count"], title=d["title"], quote=d["quote"], beats=beats_ui))
        for i, (rel_start, b, a) in enumerate(lines):
            start = t + rel_start
            nxt = t + lines[i + 1][0] if i + 1 < len(lines) else t + scene_len
            cap = dict(start=round(start, 3), end=round(min(nxt - 0.1, start + duration(a) + 0.5), 3))
            if b[0] == "narr":
                cap.update(kind="narr", text=b[1])
            elif b[0] == "app":
                cap.update(kind="app", label="AccessPoint", text=f"“{b[1]}”", sub=b[2])
            else:
                cap.update(kind="user", label=b[2], text=f"“{b[3]}”")
            captions.append(cap)
            audio.append((start, a, "app" if b[0] == "app" else "voice"))
        print(f"  {d['id']:9s} {scene_len:5.1f}s  taps at {', '.join(f'{c - clip_start:.1f}' for c in changes)}")
        t += scene_len

    demo_span = (scenes[f"demo-{DEMOS[0]['id']}"]["start"], t)
    add_static(OUTRO)
    total = round(t, 3)
    print(f"total {total:.1f}s (limit {LIMIT}s)")
    if total > LIMIT:
        sys.exit("Over the limit: shorten scenes or spoken lines.")

    m = scenes["arch"]["marks"]
    arch_end = scenes["arch"]["end"] - scenes["arch"]["start"]
    arch_nodes = [m[0], m[1], m[2], m[3], m[3] + 1.4, arch_end - 1.4]
    timeline = dict(duration=total, scenes=scenes, captions=captions, demos=demos, clips=clip_slots,
                    demoSpan=demo_span, archNodes=arch_nodes)
    (HERE / "timeline.js").write_text("// Generated by build.py. Do not edit by hand.\nwindow.TIMELINE = " + json.dumps(timeline, ensure_ascii=False, indent=1) + ";\n")
    (HERE / "timeline.json").write_text(json.dumps(timeline, ensure_ascii=False))

    import music
    music.render(total, HERE / "music.wav")
    inputs, filters = [], []
    for i, (start, path, kind) in enumerate(audio):
        inputs += ["-i", str(path)]
        ms = int(start * 1000)
        eq = f"{APP_EQ}," if kind == "app" else ""
        filters.append(f"[{i}:a]aresample=48000,aformat=channel_layouts=stereo,{eq}adelay={ms}|{ms}[a{i}]")
    k = len(audio)
    inputs += ["-i", str(HERE / "music.wav")]
    filters.append("".join(f"[a{i}]" for i in range(k)) + f"amix=inputs={k}:normalize=0,apad,atrim=0:{total},asplit=2[voice][key]")
    # Music sits low and ducks further whenever anyone speaks, so every word stays clear.
    filters.append(f"[{k}:a]aresample=48000,volume={MUSIC_GAIN}[bed]")
    filters.append("[bed][key]sidechaincompress=threshold=0.015:ratio=6:attack=15:release=350:makeup=1[ducked]")
    filters.append("[voice][ducked]amix=inputs=2:normalize=0,loudnorm=I=-16:TP=-1.5[out]")
    run(["ffmpeg", "-loglevel", "error", "-y", *inputs, "-filter_complex", ";".join(filters), "-map", "[out]", "-ar", "48000", str(HERE / "mix.wav")])
    print("wrote timeline.js and mix.wav")


# ---------------------------------------------------------------- compose
K = 2  # render scale: index.html is laid out at 1920x1080, the output is 3840x2160
SCREEN = dict(x=300 * K, y=118 * K, w=372 * K, h=808 * K)
FRAME = dict(x=286 * K, y=104 * K)


def cmd_compose():
    tl = json.loads((HERE / "timeline.json").read_text())
    inputs = ["-i", "base.mp4", "-i", "mix.wav", "-loop", "1", "-i", "assets/screen-mask@2x.png"]
    # rounded screen corners: the frame's outer curve is tighter than the screen inset, so the clip itself is masked
    filt, prev = ["[0:v]format=yuv420p[b0]", f"[2:v]format=gray,split={len(tl['clips'])}" + "".join(f"[m{i}]" for i in range(len(tl["clips"])))], "b0"
    for i, c in enumerate(tl["clips"]):
        n = i + 3
        inputs += ["-itsoffset", str(c["start"]), "-i", f"clips/{c['name']}.mp4"]
        filt.append(f"[{n}:v]scale={SCREEN['w']}:{SCREEN['h']}:flags=lanczos,setsar=1,tpad=stop_mode=clone:stop_duration=3,format=yuva420p[s{n}]")
        filt.append(f"[s{n}][m{i}]alphamerge[c{n}]")
        filt.append(f"[{prev}][c{n}]overlay={SCREEN['x']}:{SCREEN['y']}:enable='between(t,{c['start']},{c['end']})':eof_action=pass[v{n}]")
        prev = f"v{n}"
    n = len(tl["clips"]) + 3
    a, b = tl["demoSpan"]
    inputs += ["-loop", "1", "-i", "assets/phone-frame@2x.png"]
    filt.append(f"[{prev}][{n}:v]overlay={FRAME['x']}:{FRAME['y']}:enable='between(t,{a},{b})'[vout]")
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *inputs, "-filter_complex", ";".join(filt), "-map", "[vout]", "-map", "1:a",
         "-t", str(tl["duration"]), "-r", str(FPS), "-c:v", "libx264", "-preset", "medium", "-crf", "17", "-profile:v", "high", "-level", "5.1",
         "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "256k", "-movflags", "+faststart", str(DEMO / "accesspoint-demo.mp4")], cwd=HERE)
    print(f"wrote {DEMO / 'accesspoint-demo.mp4'} ({tl['duration']:.1f}s, 3840x2160)")


if __name__ == "__main__":
    {"flows": cmd_flows, "timeline": cmd_timeline, "compose": cmd_compose}[sys.argv[1] if len(sys.argv) > 1 else "flows"]()
