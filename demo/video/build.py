FRAME = dict(x=286 * K, y=104 * K)


def cmd_compose():
    tl = json.loads((HERE / "timeline.json").read_text())
    inputs = ["-i", "base.mp4", "-i", "mix.wav", "-loop", "1", "-i", "assets/screen-mask@2x.png"]
    # rounded screen corners: the frame's outer curve is tighter than the screen inset, so the clip itself is masked
    filt, prev = ["[0:v]format=yuv420p[b0]", f"[2:v]format=gray,split={len(tl['clips'])}" + "".join(f"[m{i}]" for i in range(len(tl["clips"])))], "b0"
    for i, c in enumerate(tl["clips"]):
        n = i + 3
        inputs += ["-itsoffset", str(c["start"]), "-i", f"clips/{c['name']}.mp4"]
        filt.append(f"[{n}:v]scale={SCREEN['w']}:{SCREEN['h']}:flags=lanczos,setsar=1,tpad=stop_mode=clone:stop_duration=3,format=yuva420p[s{n}]")
        filt.append(f"[s{n}][m{i}]alphamerge[c{n}]")
        filt.append(f"[{prev}][c{n}]overlay={SCREEN['x']}:{SCREEN['y']}:enable='between(t,{c['start']},{c['end']})':eof_action=pass[v{n}]")
        prev = f"v{n}"
    n = len(tl["clips"]) + 3
    a, b = tl["demoSpan"]
    inputs += ["-loop", "1", "-i", "assets/phone-frame@2x.png"]
