    (HERE / "timeline.js").write_text("// Generated by build.py. Do not edit by hand.\nwindow.TIMELINE = " + json.dumps(timeline, ensure_ascii=False, indent=1) + ";\n")
    (HERE / "timeline.json").write_text(json.dumps(timeline, ensure_ascii=False))

    import music
    music.render(total, HERE / "music.wav")
    inputs, filters = [], []
    for i, (start, path, kind) in enumerate(audio):
        inputs += ["-i", str(path)]
        ms = int(start * 1000)
        eq = f"{APP_EQ}," if kind == "app" else ""
        filters.append(f"[{i}:a]aresample=48000,aformat=channel_layouts=stereo,{eq}adelay={ms}|{ms}[a{i}]")
    k = len(audio)
    inputs += ["-i", str(HERE / "music.wav")]
    filters.append("".join(f"[a{i}]" for i in range(k)) + f"amix=inputs={k}:normalize=0,apad,atrim=0:{total},asplit=2[voice][key]")
    # Music sits low and ducks further whenever anyone speaks, so every word stays clear.
    filters.append(f"[{k}:a]aresample=48000,volume={MUSIC_GAIN}[bed]")
    filters.append("[bed][key]sidechaincompress=threshold=0.015:ratio=6:attack=15:release=350:makeup=1[ducked]")
    filters.append("[voice][ducked]amix=inputs=2:normalize=0,loudnorm=I=-16:TP=-1.5[out]")
    run(["ffmpeg", "-loglevel", "error", "-y", *inputs, "-filter_complex", ";".join(filters), "-map", "[out]", "-ar", "48000", str(HERE / "mix.wav")])
    print("wrote timeline.js and mix.wav")


