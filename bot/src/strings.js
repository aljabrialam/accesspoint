// Where a box sits in the photo, in plain words (from SAM 3.1 coordinates, not from a model).
export function position(L, box) {
  const cx = (box.x1 + box.x2) / 2 / box.w, cy = (box.y1 + box.y2) / 2 / box.h;
  const v = cy < 0.36 ? L.pos.top : cy > 0.64 ? L.pos.bottom : L.pos.middle;
  const h = cx < 0.36 ? L.pos.left : cx > 0.64 ? L.pos.right : L.pos.center;
  return v === h ? v : `${v}, ${h}`;
}
