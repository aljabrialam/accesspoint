    scenes, captions, audio, demos, clip_slots = {}, [], [], [], []

    def add_static(scene_list):
        nonlocal t
        for sid, section, badge, min_dur, lines in scene_list:
            cursor, marks = 0.3, []
            for kind, text in lines:
                a = tts(text, HERO_VOICE if kind == "hero" else NARRATOR)
                marks.append(round(cursor, 3))
                captions.append(dict(start=round(t + cursor, 3), end=round(t + cursor + duration(a) + 0.2, 3), kind="narr", text=text))
                audio.append((t + cursor, a, "voice"))
                cursor += duration(a) + LINE_GAP
            dur = max(min_dur, cursor - LINE_GAP + TAIL.get(sid, 0.5))
            scenes[sid] = dict(start=round(t, 3), end=round(t + dur, 3), section=section, badge=badge, marks=marks)
            t += dur

    add_static(INTRO)
    for d in DEMOS:
        raw, cfr = DEMO / "clips/raw" / f"{d['id']}.mp4", DEMO / "clips/cfr" / f"{d['id']}.mp4"
        run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(raw), "-vf", "fps=30", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-an", str(cfr)])
        changes = screen_changes(cfr, d.get("scene", 0.05))
        n_taps = sum(1 if b[0] == "tap" else 2 for b in d["beats"] if b[0] in ("tap", "say"))
        if len(changes) < n_taps:
            sys.exit(f"{d['id']}: expected {n_taps} screen changes, found {len(changes)} ({changes}). Re-record this clip.")
        changes = changes[:n_taps]

        # Lay out spoken lines: lines before the first tap play from the start; later lines follow their tap.
        pre = [b for b in d["beats"][: next(i for i, b in enumerate(d["beats"]) if b[0] in ("tap", "say"))]]
        pre_len = 0.4 + sum(duration(line_audio(b, clips)) + GAP for b in pre)
        clip_start = changes[0] - pre_len
        if clip_start < 0:
            sys.exit(f"{d['id']}: not enough footage before the first tap ({changes[0]:.1f}s, need {pre_len:.1f}s).")
        rel, ci, lines, beats_ui = 0.4, 0, [], [(0.0, *d["status"])]
        cursor = 0.4
        for b in d["beats"]:
            if b[0] == "tap":
                tap_rel = changes[ci] - clip_start
                ci += 1
                beats_ui.append((round(tap_rel, 3), *b[2]))
                cursor = max(cursor, tap_rel + AFTER_TAP)
            elif b[0] == "say":
                mic_rel, chip_rel = changes[ci] - clip_start, changes[ci + 1] - clip_start
                ci += 2
                a = line_audio(b, clips)
                lines.append((max(mic_rel + 0.25, chip_rel - duration(a) - 0.05), b, a))
                beats_ui.append((round(chip_rel, 3), *b[4]))
                cursor = max(cursor, chip_rel + AFTER_TAP)
            else:
                a = line_audio(b, clips)
                lines.append((cursor, b, a))
                cursor += duration(a) + GAP
        scene_len = max(cursor + 0.5, changes[-1] - clip_start + 1.5)
        if clip_start + scene_len > duration(cfr):
            sys.exit(f"{d['id']}: recording too short for the planned audio. Re-run `python3 build.py flows` and re-record.")

        run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(cfr), "-ss", f"{clip_start:.3f}", "-t", f"{scene_len:.3f}", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-an", str(HERE / "clips" / f"{d['id']}.mp4")])
        scenes[f"demo-{d['id']}"] = dict(start=round(t, 3), end=round(t + scene_len, 3), section=d["section"], badge="Scenario mode, demo kiosk we built")
        clip_slots.append(dict(name=d["id"], start=round(t, 3), end=round(t + scene_len, 3)))
        demos.append(dict(start=round(t, 3), end=round(t + scene_len, 3), count=d["count"], title=d["title"], quote=d["quote"], beats=beats_ui))
        for i, (rel_start, b, a) in enumerate(lines):
            start = t + rel_start
            nxt = t + lines[i + 1][0] if i + 1 < len(lines) else t + scene_len
            cap = dict(start=round(start, 3), end=round(min(nxt - 0.1, start + duration(a) + 0.5), 3))
            if b[0] == "narr":
                cap.update(kind="narr", text=b[1])
            elif b[0] == "app":
                cap.update(kind="app", label="AccessPoint", text=f"“{b[1]}”", sub=b[2])
            else:
                cap.update(kind="user", label=b[2], text=f"“{b[3]}”")
            captions.append(cap)
            audio.append((start, a, "app" if b[0] == "app" else "voice"))
        print(f"  {d['id']:9s} {scene_len:5.1f}s  taps at {', '.join(f'{c - clip_start:.1f}' for c in changes)}")
        t += scene_len

    demo_span = (scenes[f"demo-{DEMOS[0]['id']}"]["start"], t)

    chats = []
    for c in CHATS:
        msgs = json.loads((HERE / "assets/chat" / f"{c['id']}.json").read_text())
        for at, text in c["lines"]:
            a = tts(text, NARRATOR)
            captions.append(dict(start=round(t + at, 3), end=round(t + at + duration(a) + 0.2, 3), kind="narr", text=text))
            audio.append((t + at, a, "voice"))
        voices = []
        for at, idx, max_s in c["voice"]:
            src = HERE / "assets/chat" / msgs[idx]["voice"]
